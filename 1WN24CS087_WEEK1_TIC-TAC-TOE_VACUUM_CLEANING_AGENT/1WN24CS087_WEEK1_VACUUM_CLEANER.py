def run_vacuum_simulation():
    print("--- Vacuum Cleaner Agent Simulation ---")

    # 1. Take inputs for the environment state
    location = input("Enter current vacuum location (A or B): ").strip().upper()
    status_A = input("Enter status of Location A (Clean or Dirty): ").strip().capitalize()
    status_B = input("Enter status of Location B (Clean or Dirty): ").strip().capitalize()

    # Store environment state in a dictionary
    environment_status = {"A": status_A, "B": status_B}

    print(f"\nInitial State: Vacuum is at {location}. Room A is {status_A}, Room B is {status_B}.\n")

    # 2. Execution loop until both locations are clean
    steps = 0
    max_steps = 4 # Safety limit to prevent infinite loops

    while (environment_status["A"] == "Dirty" or environment_status["B"] == "Dirty") and steps < max_steps:
        steps += 1
        current_status = environment_status[location]

        # Agent decides the action based on its current perception
        action = reflex_vacuum_agent(location, current_status)
        print(f"[Step {steps}] Location: {location} | Status: {current_status} -> Action Chosen: {action}")

        # 3. Apply the action to change the environment
        if action == "Suck":
            environment_status[location] = "Clean"
            print(f"-> Success: Location {location} has been cleaned.")
        elif action == "Right":
            location = "B"
            print("-> Success: Moved right to Location B.")
        elif action == "Left":
            location = "A"
            print("-> Success: Moved left to Location A.")

        print(f"Current Environment Status: Room A: {environment_status['A']}, Room B: {environment_status['B']}\n")

    # Final Goal check
    if environment_status["A"] == "Clean" and environment_status["B"] == "Clean":
        print("Goal Reached: Both locations are fully clean!")
    else:
        print("Simulation stopped.")

if __name__ == "__main__":
    run_vacuum_simulation()