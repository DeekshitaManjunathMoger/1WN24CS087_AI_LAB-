import math

# Initialize the board
board = [' ' for _ in range(9)]

def print_board(b):
    print(f"\n {b[0]} | {b[1]} | {b[2]} ")
    print("---|---|---")
    print(f" {b[3]} | {b[4]} | {b[5]} ")
    print("---|---|---")
    print(f" {b[6]} | {b[7]} | {b[8]} \n")

def is_winner(b, letter):
    # Check rows, columns, and diagonals
    winning_conditions = [
        (0, 1, 2), (3, 4, 5), (6, 7, 8),  # Rows
        (0, 3, 6), (1, 4, 7), (2, 5, 8),  # Columns
        (0, 4, 8), (2, 4, 6)             # Diagonals
    ]
    return any(b[i] == b[j] == b[k] == letter for i, j, k in winning_conditions)

def is_board_full(b):
    return ' ' not in b

def get_empty_cells(b):
    return [i for i, spot in enumerate(b) if spot == ' ']

# Minimax algorithm for unbeatable AI
def minimax(b, is_maximizing):
    if is_winner(b, 'O'):
        return 1
    if is_winner(b, 'X'):
        return -1
    if is_board_full(b):
        return 0

    if is_maximizing:
        best_score = -math.inf
        for cell in get_empty_cells(b):
            b[cell] = 'O'
            score = minimax(b, False)
            b[cell] = ' '
            best_score = max(score, best_score)
        return best_score
    else:
        best_score = math.inf
        for cell in get_empty_cells(b):
            b[cell] = 'X'
            score = minimax(b, True)
            b[cell] = ' '
            best_score = min(score, best_score)
        return best_score

def ai_move(b):
    best_score = -math.inf
    move = None
    for cell in get_empty_cells(b):
        b[cell] = 'O'
        score = minimax(b, False)
        b[cell] = ' '
        if score > best_score:
            best_score = score
            move = cell
    b[move] = 'O'

def player_move(b):
    while True:
        try:
            choice = int(input("Choose a position (0-8): "))
            if b[choice] == ' ':
                b[choice] = 'X'
                break
            else:
                print("That spot is taken! Try again.")
        except (ValueError, IndexError):
            print("Invalid input. Enter a number between 0 and 8.")

# Main Game Loop
print("Welcome to Tic-Tac-Toe!")
print("You are 'X' and the AI is 'O'.")
print_board(board)

while True:
    player_move(board)
    print_board(board)
    if is_winner(board, 'X'):
        print("You win!")
        break
    if is_board_full(board):
        print("It's a tie!")
        break

    print("AI's turn...")
    ai_move(board)
    print_board(board)
    if is_winner(board, 'O'):
        print("AI wins!")
        break
    if is_board_full(board):
        print("It's a tie!")
        break

import random
import time

class VacuumEnvironment:
    def __init__(self):
        # Randomly initialize rooms as 'Clean' or 'Dirty'
        self.rooms = {
            'A': random.choice(['Clean', 'Dirty']),
            'B': random.choice(['Clean', 'Dirty'])
        }
        # Place the agent in a random starting room
        self.agent_location = random.choice(['A', 'B'])
        self.performance_score = 0

    def get_percept(self):
        """Returns the current location and its status."""
        status = self.rooms[self.agent_location]
        return self.agent_location, status

    def execute_action(self, action):
        """Applies the agent's action to the environment."""
        print(f"Action Executed: {action}")

        if action == 'Suck':
            self.rooms[self.agent_location] = 'Clean'
            self.performance_score += 10  # Reward for cleaning
        elif action == 'Right' and self.agent_location == 'A':
            self.agent_location = 'B'
            self.performance_score -= 1   # Small penalty for moving
        elif action == 'Left' and self.agent_location == 'B':
            self.agent_location = 'A'
            self.performance_score -= 1   # Small penalty for moving

    def display_status(self):
        print(f"Environment State: {self.rooms} | Agent Position: {self.agent_location} | Score: {self.performance_score}")
        print("-" * 65)


